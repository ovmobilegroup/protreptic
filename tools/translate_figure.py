def translate_text(text):
    """简单的英译文函数"""
    if not text:
        return text
    
    # 基本映射
    translations = {
        # 陈云相关术语
        "鸟笼经济": "cage economy",
        "边界思维": "boundary thinking",
        "四面出击": "encirclement from all sides",
        "两面开花": "blooming on all sides",
        
        # 钱学森相关术语
        "理论力学": "theoretical mechanics", 
        "控制论": "cybernetics",
        "系统工程": "systems engineering",
        "航天科技": "space technology",
        
        # 邓稼先相关术语
        "原子弹": "atomic bomb",
        "氢弹": "hydrogen bomb",
        "核能": "nuclear energy",
        "两弹一星": "two bombs and one satellite",
        
        # 万里相关术语
        "开放政策": "open policy",
        "经济改革": "economic reform",
        "改革开放": "reform and opening up",
        
        # 宋庆龄相关术语
        "人民革命": "people's revolution",
        "民主": "democracy",
        "和平": "peace",
        "国际主义": "internationalism",
    }
    
    result = text
    for zh, en in translations.items():
        result = result.replace(zh, en)
    
    # 处理一些句子结构
    if "且" in result and "while" not in result:
        result = result.replace("且", "and")
    if "，" in result:
        result = result.replace("，", ", ")
    if "。" in result:
        result = result.replace("。", " ")
    
    return result

def filter_empty(data):
    """过滤空字段"""
    filtered = {}
    for key, value in data.items():
        if value:
            if isinstance(value, str) and value.strip():
                filtered[key] = value
            elif isinstance(value, list) and value:
                filtered[key] = value
            elif isinstance(value, dict) and value:
                filtered[key] = value
    return filtered

